package com.atleta.demo.enums;

/**
 * Resultado de un partido desde la perspectiva de un jugador específico.
 */
public enum MatchResult {
    /**
     * El equipo del jugador ganó el partido
     */
    VICTORIA,
    
    /**
     * El equipo del jugador perdió el partido
     */
    DERROTA,
    
    /**
     * El partido terminó en empate
     */
    EMPATE
}