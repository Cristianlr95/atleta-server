CREATE TABLE team_captain_transfers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id BIGINT NOT NULL REFERENCES teams(id),
    outgoing_captain_uuid UUID NOT NULL REFERENCES player_profiles(atleta_uuid),
    incoming_captain_uuid UUID NOT NULL REFERENCES player_profiles(atleta_uuid),
    actor_uuid UUID NOT NULL REFERENCES player_profiles(atleta_uuid),
    transferred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_team_captain_transfer_distinct CHECK (outgoing_captain_uuid <> incoming_captain_uuid)
);

CREATE INDEX idx_team_captain_transfers_team ON team_captain_transfers(team_id, id);
